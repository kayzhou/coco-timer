enum ChineseNumber {
    static func gua(_ number: Int) -> String {
        "第\(spell(number))卦"
    }

    static func spell(_ number: Int) -> String {
        let digits = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"]
        switch number {
        case 1...9:
            return digits[number]
        case 10:
            return "十"
        case 11...19:
            return "十" + digits[number - 10]
        case 20, 30, 40, 50, 60:
            return digits[number / 10] + "十"
        case 21...29, 31...39, 41...49, 51...59, 61...64:
            return digits[number / 10] + "十" + digits[number % 10]
        default:
            return "\(number)"
        }
    }
}
